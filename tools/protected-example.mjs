import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),P=require('../src/protected-project.js'),A=require('../src/project-accounts.js'),C=require('../src/core.js');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const demo=JSON.parse(await fs.readFile(path.join(root,'site/demo-data.json'),'utf8'));
const data=C.validateAndJoin(demo.students,demo.keys?.length?demo.keys:null,demo.groups);
const center=data.students.find(r=>r.ID==='00253')?.Centro||data.students[0].Centro;
const aulas=P.classes(data).filter(c=>c.center===center&&c.course==='1.º ESO');
const a=aulas.find(c=>c.group==='A'),b=aulas.find(c=>c.group==='B');
if(!a||!b)throw Error('La demo no contiene las aulas de prueba.');
const accounts=A.accounts(A.plan(data,center),true,{orientationPassword:'FRJ508'});
const example=await P.build({data,center,accounts});
const output=path.join(root,'revision-local');await fs.mkdir(output,{recursive:true});
await fs.writeFile(path.join(output,'Centro_pruebas.pbis'),example.text);
await fs.writeFile(path.join(output,'Registro_pruebas.json'),JSON.stringify(example.manifest,null,2));
await fs.writeFile(path.join(output,'ACCESOS_DE_PRUEBA.docx'),A.credentialsDocx({...example,center,accounts}));
await fs.writeFile(path.join(output,'Centro_pruebas_y_accesos.zip'),A.bundle(example,center,accounts).bytes);
await fs.copyFile(path.join(root,'release/PBIS.html'),path.join(output,'PBIS.html'));
console.log(JSON.stringify({output,center,students:data.students.filter(r=>r.Centro===center).length,aulaA:a.key,aulaB:b.key,bytes:Buffer.byteLength(example.text)}));
